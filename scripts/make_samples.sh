#!/usr/bin/env bash
# Generate the judge pack ON A DOCKER HOST: real engine outputs and prep artefacts for sample mode.
# Requires: activesite-engine:at26 and activesite-prep:at26 built, uv sync done, docker compose up -d (optional).
# Writes data/sample/<case>/{charge<±N>,attempt<N>}/sp.out, data/sample/<case>/prep/, samples/<case>/{report.md,cards.json,trace.jsonl,stats.json}
# and data/sample/MANIFEST.md with the date and commit. Nothing here is hand-written.
set -euo pipefail
cd "$(dirname "$0")/.."
export SAMPLE_MODE=false
CASES=(ippoi_site_a ippoi_site_b egfr_erlotinib abl_imatinib_a abl_imatinib_b)
SAMPLE_CASES=(ippoi_site_a ippoi_site_b egfr_erlotinib)
STAMP=$(date -u +%Y-%m-%dT%H:%M:%SZ)
COMMIT=$(git rev-parse HEAD)

echo "== reset memory so site A runs cold and site B warm"
rm -f data/memory/hmem.sqlite logs/hmem_ledger.jsonl

run_case () {
  local case="$1"
  echo "== $case"
  uv run python run.py --case "$case" --docker --json > "/tmp/activesite_${case}.json"
  python3 - "$case" "/tmp/activesite_${case}.json" <<'PY'
import json, shutil, sys, re
from pathlib import Path
case, path = sys.argv[1], sys.argv[2]
st = json.loads(Path(path).read_text())
run_id = st["run_id"]
runs = Path("data/runs") / run_id
dst = Path("data/sample") / case
dst.mkdir(parents=True, exist_ok=True)
# engine outputs, keyed by attempt and by the charge echoed in the namelist
for sp in sorted(runs.glob("*/sp.out")):
    text = sp.read_text(errors="replace")
    m = re.search(r"^\s*qmcharge\s*=\s*([-+]?\d+)", text, re.M)
    charge = int(m.group(1)) if m else None
    (dst / sp.parent.name).mkdir(exist_ok=True)
    shutil.copy(sp, dst / sp.parent.name / "sp.out")
    if charge is not None:
        (dst / f"charge{charge:+d}").mkdir(exist_ok=True)
        shutil.copy(sp, dst / f"charge{charge:+d}" / "sp.out")
# prep artefacts for ligand cases
if st.get("kind") == "ligand" and (runs / "prep.json").exists():
    (dst / "prep").mkdir(exist_ok=True)
    for name in ("complex.parm7", "min.rst7", "pdb2pqr.log", "ligand.mol2", "prep.json"):
        if (runs / name).exists():
            shutil.copy(runs / name, dst / "prep" / name)
# sample run outputs
if case in ("ippoi_site_a", "ippoi_site_b", "egfr_erlotinib"):
    out = Path("samples") / case
    out.mkdir(parents=True, exist_ok=True)
    shutil.copy(Path("cases") / f"{case}.json", out / "input.json")
    shutil.copy(st["report"], out / "report.md")
    shutil.copy(st["cards"], out / "cards.json")
    shutil.copy(st["trace"], out / "trace.jsonl")
    (out / "stats.json").write_text(json.dumps(st, indent=1, default=str))
print(f"{case}: run {run_id} retries={st['retries']} memory_used={st['memory_used']} qm_ok={st['qm_ok']} ESCF={st['qm_escf_kcal']}")
PY
}

for c in "${CASES[@]}"; do run_case "$c"; done
echo "== cold site B (so a cold sample-mode run of site B also has its odd-electron attempt)"
rm -f data/memory/hmem.sqlite logs/hmem_ledger.jsonl
run_case ippoi_site_b

{
  echo "# data/sample — cached engine outputs for sample mode"
  echo
  echo "Generated by scripts/make_samples.sh on a Docker host."
  echo
  echo "- date: $STAMP"
  echo "- commit: $COMMIT"
  echo "- engine image: activesite-engine:at26; prep image: activesite-prep:at26"
  echo "- cases: ${CASES[*]} (site B run warm and cold)"
  echo
  echo "Every sp.out here is the verbatim sander mdout of that run; prep/ holds the real tleap topology, minimised"
  echo "coordinates, pdb2pqr log, ligand mol2 and the setup evidence (prep.json). SAMPLE_MODE replays these and labels"
  echo "every result 'cached engine output (sample mode)'."
} > data/sample/MANIFEST.md
echo "== done; review data/sample and samples/, then commit"
